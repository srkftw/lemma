def _display(path: Path, root: Path) -> str:
    try:
        return str(path.resolve().relative_to(root.resolve()))
    except ValueError:
        return str(path.resolve())


def _safe_build_subdirectory(path: Path, root: Path) -> bool:
    build_root = (root / "build").resolve()
    resolved = path.resolve()
    try:
        relative = resolved.relative_to(build_root)
    except ValueError:
        return False
    return bool(relative.parts)


def prepare_output_directory(path: Path, root: Path, *, clean: bool) -> None:
    """Create an empty output directory, only deleting known build subtrees."""
    if path.exists() and any(path.iterdir()):
        if not clean:
            raise Core0Error(
                f"output directory is not empty: {path}; pass --clean for a build/ subtree"
            )
        if not _safe_build_subdirectory(path, root):
            raise Core0Error(f"refusing to clean a directory outside {root / 'build'}: {path}")
        shutil.rmtree(path)
    path.mkdir(parents=True, exist_ok=True)


def invalidate_output_file(path: Path, root: Path) -> None:
    """Remove one generated result only when its parent is a safe build subtree."""
    if not path.exists() and not path.is_symlink():
        return
    build_root = (root / "build").resolve()
    parent = path.parent.resolve()
    try:
        relative_parent = parent.relative_to(build_root)
    except ValueError as error:
        raise Core0Error(
            f"refusing to invalidate an output outside {build_root}: {path}"
        ) from error
    if not relative_parent.parts:
        raise Core0Error(f"refusing to invalidate an output at the build root: {path}")
    if path.is_dir() and not path.is_symlink():
        raise Core0Error(f"refusing to invalidate a directory as a result file: {path}")
    path.unlink()


def _invoke(
    command_log: list[dict[str, object]],
    argv: Sequence[str],
    *,
    cwd: Path,
    root: Path,
    timeout_seconds: float,
    env: Mapping[str, str] | None = None,
) -> None:
    if Path(argv[0]).name == "lake":
        from build_actions import controlled_environment
        allowed = {"LEMMA_CORE0_OUT", "LEMMA_TRAP_RESTORE_MUTATION", "LEMMA_TIMER_MUTATION"}
        allowed.update("LEMMA_" + family + "_" + field for family in ("SCALAR", "MEMORY", "DEVICE")
                       for field in ("SUITE_ID", "SOURCE_SEED", "RUNTIME_SEED"))
        supplied = {} if env is None else {k:v for k,v in env.items() if k in allowed}
        env = controlled_environment(require_tools(("lean", "lake", "clang", "ld.lld")), supplied)
    result = checked(argv, cwd=cwd, timeout_seconds=timeout_seconds, env=env)
    command_log.append(
        {
            "argv": list(argv),
            "cwd": _display(cwd, root),
            "returncode": result.returncode,
            "elapsed_seconds": round(result.elapsed_seconds, 6),
            "stdout": result.stdout.decode("utf-8", errors="replace"),
            "stderr": result.stderr.decode("utf-8", errors="replace"),
            **({"environment": dict(env)} if env is not None else {}),
        }
    )


def _version(tool: str, root: Path) -> str:
    candidates = {
        "lean": ("lean", "--version"),
        "lake": ("lake", "--version"),
        "opt": ("opt", "--version"),
        "llc": ("llc", "--version"),
        "clang": ("clang", "--version"),
        "ld.lld": ("ld.lld", "--version"),
        "qemu-system-riscv64": ("qemu-system-riscv64", "--version"),
        "dtc": ("dtc", "--version"),
    }
    result = checked(candidates[tool], cwd=root, timeout_seconds=15)
    text = (result.stdout + result.stderr).decode("utf-8", errors="replace").strip()
    if not text:
        raise Core0Error(f"{tool} produced an empty version identity")
    return text


def _source_hashes(
    root: Path,
    export_source: Path,
    additional_source_inputs: Sequence[Path] = (),
) -> list[dict[str, str]]:
    paths: list[Path] = []
    if (root / "docs/document-map.json").is_file(): paths.append(root / "docs/document-map.json")
    paths.extend(root / value for value in SOURCE_INPUTS)
    paths.extend(root / value for value in ("scripts/action_cache.py", "scripts/action_worker.py", "scripts/build_actions.py", "scripts/build_dependencies.py", "scripts/build_admission.py") if (root/value).is_file())
    paths.extend(sorted((root / "Lemma").rglob("*.lean")))
    paths.append(root / "Lemma.lean")
    paths.append(root / "examples/core0/Positive.lean")
    paths.append(export_source)
    for value in additional_source_inputs:
        path = Path(value)
        paths.append(path if path.is_absolute() else root / path)
    unique: dict[Path, None] = {}
    for path in paths:
        unique[path.resolve()] = None
    missing = [str(path) for path in unique if not path.is_file()]
    if missing:
        raise Core0Error("missing source/configuration inputs: " + ", ".join(missing))
    return [
        {"path": _display(path, root), "sha256": sha256(path)}
        for path in sorted(unique, key=lambda item: _display(item, root))
    ]


def _elaboration_paths(root: Path, source: Path) -> tuple[Path, Path]:
    resolved = (root / source).resolve() if not source.is_absolute() else source.resolve()
    try:
        relative = resolved.relative_to(root.resolve())
    except ValueError as error:
        raise Core0Error(f"Lean elaboration source escapes the repository: {source}") from error
    if relative.suffix != ".lean" or not resolved.is_file():
        raise Core0Error(f"Lean elaboration source is missing or has the wrong suffix: {source}")
    output = root / ".lake/build/lib/lean" / relative.with_suffix(".olean")
    return resolved, output


def _validate_artifact_request(
    artifact_category: str,
    compiler_fault_manifest: str | None,
) -> None:
    if artifact_category not in ARTIFACT_CATEGORIES:
        raise Core0Error(
            f"unsupported artifact category {artifact_category!r}; expected one of "
            + ", ".join(ARTIFACT_CATEGORIES)
        )
    if artifact_category == "test-compiler-mutant":
        if compiler_fault_manifest != COMPILER_FAULT_MANIFEST:
            raise Core0Error(
                "test-compiler-mutant builds require the generated "
                f"{COMPILER_FAULT_MANIFEST} manifest"
            )
    elif compiler_fault_manifest is not None:
        raise Core0Error(
            f"{artifact_category} builds forbid a compiler-fault manifest"
        )


def _compiler_fault_provenance(output_dir: Path, manifest_name: str) -> dict[str, str]:
    manifest_path = output_dir / manifest_name
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise Core0Error(f"invalid generated compiler-fault manifest: {error}") from error
    expected = {
        "schema_version": 1,
        "artifact_category": "test-compiler-mutant",
        "transform_stage": "structured-llvm-pre-optimization",
        "production_selectable": False,
        "match_count": 1,
    }
    if not isinstance(manifest, dict):
        raise Core0Error("generated compiler-fault manifest is not an object")
    mismatches = {
        field: (manifest.get(field), value)
        for field, value in expected.items()
        if manifest.get(field) != value
    }
    if mismatches:
        raise Core0Error(
            "generated compiler-fault manifest has invalid quarantine fields: "
            + repr(mismatches)
        )
    for field in (
        "source_root",
        "fault",
        "target_source",
        "target_llvm",
        "before",
        "after",
    ):
        if not isinstance(manifest.get(field), str) or not manifest[field]:
            raise Core0Error(
                f"generated compiler-fault manifest has an invalid {field!r} field"
            )
    return {
        "manifest_path": manifest_name,
        "manifest_sha256": sha256(manifest_path),
        "program_ll_sha256": sha256(output_dir / "program.ll"),
    }


