def _git_metadata(root: Path) -> tuple[str, list[str]]:
    commit_result = checked(
        ("git", "rev-parse", "HEAD"), cwd=root, timeout_seconds=15
    )
    commit = commit_result.stdout.decode("ascii", errors="strict").strip()
    if len(commit) != 40:
        raise Core0Error(f"unexpected Git commit identity: {commit!r}")
    status_result = checked(
        ("git", "status", "--porcelain=v1", "--untracked-files=all"),
        cwd=root,
        timeout_seconds=15,
    )
    dirty = status_result.stdout.decode("utf-8", errors="strict").splitlines()
    return commit, dirty


def capture_platform_dtb(
    *,
    output_dir: Path,
    root: Path,
    command_log: list[dict[str, object]],
    timeout_seconds: float,
) -> tuple[Path, Path, list[str]]:
    """Capture QEMU's deterministic machine DTB without booting guest code."""
    qemu_argv = [
        "qemu-system-riscv64",
        "-machine",
        "virt,acpi=off,dumpdtb=platform.dtb",
        "-accel",
        "tcg",
        "-cpu",
        "rv64",
        "-smp",
        "1",
        "-m",
        "128M",
        "-bios",
        "none",
        "-nodefaults",
        "-nic",
        "none",
        "-display",
        "none",
        "-serial",
        "none",
        "-monitor",
        "none",
        "-no-reboot",
        "-seed",
        "1",
    ]
    _invoke(
        command_log,
        qemu_argv,
        cwd=output_dir,
        root=root,
        timeout_seconds=timeout_seconds,
    )
    dtb = output_dir / "platform.dtb"
    if not dtb.is_file() or dtb.stat().st_size == 0:
        raise Core0Error("QEMU did not create a nonempty platform.dtb")
    dts_argv = ["dtc", "-I", "dtb", "-O", "dts", "-o", "platform.dts", "platform.dtb"]
    _invoke(
        command_log,
        dts_argv,
        cwd=output_dir,
        root=root,
        timeout_seconds=timeout_seconds,
    )
    dts = output_dir / "platform.dts"
    if not dts.is_file() or dts.stat().st_size == 0:
        raise Core0Error("dtc did not create a nonempty platform.dts")
    return dtb, dts, qemu_argv


def _serialized_lean(function):
    @wraps(function)
    def serialized(*args, **kwargs):
        root = Path(kwargs["root"])
        lock_path = root / "build/lake.lock"
        lock_path.parent.mkdir(parents=True, exist_ok=True)
        with lock_path.open("a+b") as lock:
            fcntl.flock(lock, fcntl.LOCK_EX)
            with action_lease(lock.fileno()):
                return function(*args, **kwargs)
    return serialized


@_serialized_lean
def build(
    *,
    root: Path,
    output_dir: Path,
    opt_level: str,
    export_source: Path,
    clean: bool = False,
    build_lean: bool = True,
    timeout_seconds: float = 180.0,
    artifact_category: str = "release",
    compiler_fault_manifest: str | None = None,
    additional_source_inputs: Sequence[Path] = (),
    elaboration_sources: Sequence[Path] = (),
    export_environment: Mapping[str, str] | None = None,
    fresh: bool = True,
    cache_dir: Path | None = None,
) -> dict[str, object]:
    _validate_artifact_request(artifact_category, compiler_fault_manifest)
    if opt_level not in OPT_PASSES:
        raise Core0Error(f"unsupported optimization profile: {opt_level}")
    tools = require_tools(
        (
            "git",
            "lean",
            "lake",
            "opt",
            "llc",
            "clang",
            "ld.lld",
            "qemu-system-riscv64",
            "dtc",
        )
    )
    export_source = export_source.resolve()
    if not export_source.is_file():
        raise Core0Error(f"Lean export driver is missing: {export_source}")
    prepare_output_directory(output_dir, root, clean=clean)
    commands: list[dict[str, object]] = []

    # Core0 shares the LLVM boundaries; its source-negative Lean elaborations
    # deliberately remain fresh under the existing qualification contract.
    from build_actions import BuildActions
    action_tools = {**tools, **require_tools(("llvm-objcopy",))}
    actions = BuildActions(root, output_dir, action_tools, timeout_seconds, commands,
                           fresh=fresh, cache_dir=cache_dir)
    actions.provenance.pop("source_archive", None)
    actions.provenance["archive_scope"] = (
        "LLVM immutable action inputs retained by producer.input_archive_sha256; "
        "broader Core0 Lean/source provenance is recorded as hashes in provenance.json")
    def invoke(log, argv, **options):
        if Path(argv[0]).name in {"opt", "llc", "clang", "ld.lld"}:
            if actions.invoke(argv, options["cwd"], options.get("env")) is not None:
                return
        _invoke(log, argv, **options)

    if build_lean:
        invoke(
            commands,
            ("lake", "build"),
            cwd=root,
            root=root,
            timeout_seconds=timeout_seconds,
        )

    # `examples` is deliberately outside the Lemma library.  Produce its olean
    # through Lean elaboration so the export driver imports the exact checked source.
    positive_olean = root / ".lake/build/lib/lean/examples/core0/Positive.olean"
    positive_olean.parent.mkdir(parents=True, exist_ok=True)
    positive_command = (
        "lake",
        "env",
        "lean",
        "-o",
        str(positive_olean.relative_to(root)),
        "examples/core0/Positive.lean",
    )
    invoke(
        commands,
        positive_command,
        cwd=root,
        root=root,
        timeout_seconds=timeout_seconds,
    )
    elaborated_inputs: list[dict[str, object]] = [
        {
            "source": "examples/core0/Positive.lean",
            "source_sha256": sha256(root / "examples/core0/Positive.lean"),
            "olean": str(positive_olean.relative_to(root)),
            "olean_sha256": sha256(positive_olean),
            "generation_command": list(positive_command),
        }
    ]
    elaborated_hash_inputs: list[Path] = [positive_olean]
    for requested_source in elaboration_sources:
        source, olean = _elaboration_paths(root, Path(requested_source))
        olean.parent.mkdir(parents=True, exist_ok=True)
        source_relative = source.relative_to(root.resolve())
        olean_relative = olean.relative_to(root.resolve())
        command = (
            "lake",
            "env",
            "lean",
            "-o",
            str(olean_relative),
            str(source_relative),
        )
        invoke(
            commands,
            command,
            cwd=root,
            root=root,
            timeout_seconds=timeout_seconds,
        )
        if not olean.is_file() or olean.stat().st_size == 0:
            raise Core0Error(f"Lean elaboration did not produce a nonempty olean: {olean_relative}")
        elaborated_inputs.append(
            {
                "source": str(source_relative),
                "source_sha256": sha256(source),
                "olean": str(olean_relative),
                "olean_sha256": sha256(olean),
                "generation_command": list(command),
            }
        )
        elaborated_hash_inputs.extend((source, olean))

    export_env = os.environ.copy()
    export_env["LEMMA_CORE0_OUT"] = str(output_dir.resolve())
    if export_environment is not None:
        if artifact_category in {
            "test-frontend-suite",
            "test-cfg-suite",
            "test-loop-suite",
        }:
            expected_export_keys = {
                "LEMMA_SCALAR_SUITE_ID",
                "LEMMA_SCALAR_SOURCE_SEED",
                "LEMMA_SCALAR_RUNTIME_SEED",
            }
            exporter_kind = "scalar"
        elif artifact_category == "test-memory-suite":
            expected_export_keys = {
                "LEMMA_MEMORY_SUITE_ID",
                "LEMMA_MEMORY_SOURCE_SEED",
                "LEMMA_MEMORY_RUNTIME_SEED",
            }
            exporter_kind = "memory"
        elif artifact_category == "test-device-suite":
            expected_export_keys = {
                "LEMMA_DEVICE_SUITE_ID",
                "LEMMA_DEVICE_SOURCE_SEED",
                "LEMMA_DEVICE_RUNTIME_SEED",
            }
            exporter_kind = "device"
        elif artifact_category == "test-trap-suite":
            expected_export_keys = {"LEMMA_TRAP_RESTORE_MUTATION"}
            exporter_kind = "trap"
        elif artifact_category == "test-timer-suite":
            expected_export_keys = {"LEMMA_TIMER_MUTATION"}
            exporter_kind = "timer"
        else:
            raise Core0Error(
                "only closed scalar/memory/device-suite test builds accept exporter configuration"
            )
        observed_export_keys = set(export_environment)
        if observed_export_keys != expected_export_keys:
            raise Core0Error(
                f"{exporter_kind} exporter configuration fields differ from the closed schema: "
                f"missing={sorted(expected_export_keys - observed_export_keys)!r}, "
                f"unexpected={sorted(observed_export_keys - expected_export_keys)!r}"
            )
        for key, value in export_environment.items():
            if not isinstance(value, str) or not value or not value.isdecimal():
                raise Core0Error(
                    f"{exporter_kind} exporter setting {key} is not a decimal natural"
                )
            parsed = int(value, 10)
            if parsed < 0 or parsed > 0xFFFFFFFFFFFFFFFF:
                raise Core0Error(
                    f"{exporter_kind} exporter setting {key} exceeds UInt64"
                )
            if artifact_category == "test-trap-suite" and parsed not in {0, 1}:
                raise Core0Error(
                    "trap exporter restore mutation must be decimal 0 or 1"
                )
            if artifact_category == "test-timer-suite" and parsed not in {0, 1, 2}:
                raise Core0Error(
                    "timer exporter mutation must be decimal 0, 1, or 2"
                )
            export_env[key] = value
    export_argv = ("lake", "env", "lean", str(export_source))
    invoke(
        commands,
        export_argv,
        cwd=root,
        root=root,
        timeout_seconds=timeout_seconds,
        env=export_env,
    )
    if artifact_category == "school-worker":
        generated_by_lean = list(SCHOOL_WORKER_GENERATED_BY_LEAN)
    elif artifact_category == "test-monitor-image":
        generated_by_lean = list(MONITOR_IMAGE_GENERATED_BY_LEAN)
    elif artifact_category == "test-timer-suite":
        generated_by_lean = list(TIMER_SUITE_GENERATED_BY_LEAN)
    elif artifact_category == "test-trap-suite":
        generated_by_lean = list(TRAP_SUITE_GENERATED_BY_LEAN)
    elif artifact_category == "test-device-suite":
        generated_by_lean = list(DEVICE_SUITE_GENERATED_BY_LEAN)
    elif artifact_category == "test-memory-suite":
        generated_by_lean = list(MEMORY_SUITE_GENERATED_BY_LEAN)
    elif artifact_category == "test-loop-suite":
        generated_by_lean = list(BOUNDED_SUITE_GENERATED_BY_LEAN)
    elif artifact_category in {"test-frontend-suite", "test-cfg-suite"}:
        generated_by_lean = list(SCALAR_SUITE_GENERATED_BY_LEAN)
    else:
        generated_by_lean = list(GENERATED_BY_LEAN)
    if compiler_fault_manifest is not None:
        generated_by_lean.append(compiler_fault_manifest)
    missing = [name for name in generated_by_lean if not (output_dir / name).is_file()]
    if missing:
        raise Core0Error("Lean exporter omitted artifacts: " + ", ".join(missing))
    unexpected_fault_manifest = output_dir / COMPILER_FAULT_MANIFEST
    if compiler_fault_manifest is None and unexpected_fault_manifest.exists():
        raise Core0Error(
            f"{artifact_category} exporter produced forbidden {COMPILER_FAULT_MANIFEST}"
        )
    compiler_fault = (
        _compiler_fault_provenance(output_dir, compiler_fault_manifest)
        if compiler_fault_manifest is not None
        else None
    )

    opt_argv = [
        "opt",
        "-S",
        f"-passes={OPT_PASSES[opt_level]}",
        "program.ll",
        "-o",
        "program.opt.ll",
    ]
    invoke(
        commands,
        opt_argv,
        cwd=output_dir,
        root=root,
        timeout_seconds=timeout_seconds,
    )

    llc_argv = [
        "llc",
        *LLC_ARGUMENTS,
        *(
            ["-stack-size-section"]
            if artifact_category in {
                "test-loop-suite",
                "test-memory-suite",
                "test-device-suite",
                "test-trap-suite",
                "test-timer-suite",
                "test-monitor-image",
                "school-worker",
            }
            else []
        ),
        f"-{opt_level}",
        "program.opt.ll",
        "-o",
        "program.o",
    ]
    invoke(
        commands,
        llc_argv,
        cwd=output_dir,
        root=root,
        timeout_seconds=timeout_seconds,
    )

    startup_argv = ["clang", *STARTUP_ARGUMENTS, "startup.S", "-o", "startup.o"]
    invoke(
        commands,
        startup_argv,
        cwd=output_dir,
        root=root,
        timeout_seconds=timeout_seconds,
    )

    link_argv = [
        "ld.lld",
        *LINK_ARGUMENTS,
        "-o",
        "image.elf",
        "startup.o",
        "program.o",
    ]
    invoke(
        commands,
        link_argv,
        cwd=output_dir,
        root=root,
        timeout_seconds=timeout_seconds,
    )
    dtb, dts, qemu_dtb_argv = capture_platform_dtb(
        output_dir=output_dir,
        root=root,
        command_log=commands,
        timeout_seconds=30.0,
    )

    required_outputs = (
        *generated_by_lean,
        "program.opt.ll",
        "program.o",
        "startup.o",
        "image.elf",
        "image.map",
        "platform.dtb",
        "platform.dts",
    )
    missing = [name for name in required_outputs if not (output_dir / name).is_file()]
    empty = [
        name
        for name in required_outputs
        if (output_dir / name).is_file() and (output_dir / name).stat().st_size == 0
    ]
    if missing or empty:
        raise Core0Error(
            f"incomplete target output (missing={missing!r}, empty={empty!r})"
        )

    commit, dirty_paths = _git_metadata(root)
    versions = {
        name: {"path": tools[name], "version": _version(name, root)}
        for name in (
            "lean",
            "lake",
            "opt",
            "llc",
            "clang",
            "ld.lld",
            "qemu-system-riscv64",
            "dtc",
        )
    }
    if artifact_category in {"test-timer-suite", "test-monitor-image"}:
        startup_provenance = {
            "path": "startup.o",
            "kind": "lean-structured-timer-startup",
            "sha256": sha256(output_dir / "startup.o"),
            "generation_command": startup_argv,
            "source": "startup.S generated by Lemma.Machine.TimerPrimitives",
            "purpose": (
                "M-mode entry, machine-timer initialization and fenced MMIO/CSR leaves, "
                "full asynchronous/synchronous trap context handling, timer probe, "
                "fatal containment, and I/O fence"
            ),
        }
    elif artifact_category == "test-trap-suite":
        startup_provenance = {
            "path": "startup.o",
            "kind": "lean-structured-trap-startup",
            "sha256": sha256(output_dir / "startup.o"),
            "generation_command": startup_argv,
            "source": "startup.S generated by Lemma.Machine.TrapPrimitives",
            "purpose": (
                "M-mode entry, full synchronous-trap context save/restore, "
                "trap probes/fatal finishers, and I/O fence"
            ),
        }
    else:
        startup_provenance = {
            "path": "startup.o",
            "kind": "lean-structured-startup",
            "sha256": sha256(output_dir / "startup.o"),
            "generation_command": startup_argv,
            "source": "startup.S generated by Lemma.Machine.Primitives",
            "purpose": "M-mode entry, BSS clearing, a0/a1 boot-input preservation, and I/O fence",
        }
    linked_inputs = [
        startup_provenance,
        _program_object_provenance(
            artifact_category,
            digest=sha256(output_dir / "program.o"),
            generation_command=llc_argv,
        ),
    ]
    provenance: dict[str, object] = {
        "schema_version": 2,
        "artifact_category": artifact_category,
        "source_commit": commit,
        "dirty_tree": bool(dirty_paths),
        "dirty_paths": dirty_paths,
        "compiler_route": "Lean Environment declaration bodies -> checked Core0 -> structured LLVM -> LLVM RV64",
        "optimization": opt_level,
        "target": {
            "triple": "riscv64-unknown-elf",
            "llvm_triple": "riscv64-unknown-unknown-elf",
            "abi": "lp64",
            "isa": "rv64im_zicsr_zifencei",
            "linker": "ld.lld direct (no driver defaults or target libraries)",
        },
        "source_inputs": _source_hashes(
            root,
            export_source,
            (*additional_source_inputs, *elaborated_hash_inputs),
        ),
        "elaborated_inputs": elaborated_inputs,
        "linked_inputs": linked_inputs,
        "link_command": link_argv,
        "tools": versions,
        "emulator_artifacts": [
            {
                "path": "platform.dtb",
                "sha256": sha256(dtb),
                "source": "pinned QEMU virt machine dumpdtb",
                "generation_command": qemu_dtb_argv,
            },
            {
                "path": "platform.dts",
                "sha256": sha256(dts),
                "source": "dtc decompilation of platform.dtb",
                "generation_command": [
                    "dtc",
                    "-I",
                    "dtb",
                    "-O",
                    "dts",
                    "-o",
                    "platform.dts",
                    "platform.dtb",
                ],
            },
        ],
        "commands": commands,
    }
    if export_environment is not None:
        provenance["export_configuration"] = {
            "driver": _display(export_source, root),
            "generation_command": list(export_argv),
            "environment": {
                key: export_environment[key]
                for key in sorted(export_environment)
            },
        }
    if compiler_fault is not None:
        provenance["compiler_fault"] = compiler_fault
    write_json(output_dir / "provenance.json", provenance)
    artifact_hashes = {
        name: sha256(output_dir / name)
        for name in sorted((*required_outputs, "provenance.json"))
    }
    record: dict[str, object] = {
        "schema_version": 1,
        "status": "pass",
        "artifact_category": artifact_category,
        "optimization": opt_level,
        "output_directory": _display(output_dir, root),
        "artifacts": artifact_hashes,
        "linked_inputs": linked_inputs,
        "platform_dtb_sha256": sha256(dtb),
    }
    write_json(output_dir / "build.json", record)
    return record


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--opt-level", choices=sorted(OPT_PASSES), default="O2")
    parser.add_argument("--output-dir", type=Path)
    parser.add_argument("--export-source", type=Path, default=Path("examples/core0/Build.lean"))
    parser.add_argument("--clean", action="store_true")
    parser.add_argument("--fresh", action="store_true", help="Bypass LLVM cache reads")
    parser.add_argument("--cache-dir", type=Path)
    parser.add_argument("--timeout", type=float, default=180.0)
    ns = parser.parse_args()
    root = repo_root()
    output = ns.output_dir or Path(f"build/core0/{ns.opt_level}")
    output = (root / output).resolve() if not output.is_absolute() else output.resolve()
    source = (
        (root / ns.export_source).resolve()
        if not ns.export_source.is_absolute()
        else ns.export_source.resolve()
    )
    try:
        record = build(
            root=root,
            output_dir=output,
            opt_level=ns.opt_level,
            export_source=source,
            clean=ns.clean,
            timeout_seconds=ns.timeout,
            fresh=ns.fresh,
            cache_dir=ns.cache_dir,
        )
    except (Core0Error, OSError, ValueError, json.JSONDecodeError) as error:
        print(f"CORE0 BUILD FAIL: {error}", file=sys.stderr)
        return 1
    print(json.dumps(record, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
