#!/usr/bin/env python3
"""Build one genuine Lean-elaborated Core0 image with an explicit RV64 closure.

This is host-only orchestration.  The target inputs are generated by the Lean
export command; this driver only invokes the pinned host tools and records their
provenance.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
from pathlib import Path
from typing import Mapping, Sequence

from core0_common import Core0Error, checked, repo_root, require_tools, sha256, write_json


OPT_PASSES = {
    "O0": "verify",
    "O2": "default<O2>",
}

LLC_ARGUMENTS = (
    "-mtriple=riscv64-unknown-elf",
    "-mattr=+m,+zicsr,+zifencei,-a,-f,-d,-c,-v,-relax",
    "-target-abi=lp64",
    "-relocation-model=static",
    "-code-model=medium",
    "-filetype=obj",
)

STARTUP_ARGUMENTS = (
    "--target=riscv64-unknown-elf",
    "-march=rv64im_zicsr_zifencei",
    "-mabi=lp64",
    "-mno-relax",
    "-c",
)

LINK_ARGUMENTS = (
    "-m",
    "elf64lriscv",
    "--no-relax",
    "-T",
    "link.ld",
    "-Map=image.map",
)

GENERATED_BY_LEAN = (
    "program.ll",
    "startup.S",
    "link.ld",
    "layout.json",
    "core0-manifest.json",
    "core0-normalized.txt",
    "symbols.txt",
)

SOURCE_INPUTS = (
    "lean-toolchain",
    "lakefile.toml",
    "lake-manifest.json",
    "flake.nix",
    "flake.lock",
    "tooling/toolchain-lock.json",
    "scripts/build_core0.py",
    "scripts/core0_common.py",
)


def _display(path: Path, root: Path) -> str:
    try:
        return str(path.resolve().relative_to(root.resolve()))
    except ValueError:
        return str(path.resolve())


def _safe_build_subdirectory(path: Path, root: Path) -> bool:
    build_root = (root / "build").resolve()
    resolved = path.resolve()
    try:
        relative = resolved.relative_to(build_root)
    except ValueError:
        return False
    return bool(relative.parts)


def prepare_output_directory(path: Path, root: Path, *, clean: bool) -> None:
    """Create an empty output directory, only deleting known build subtrees."""
    if path.exists() and any(path.iterdir()):
        if not clean:
            raise Core0Error(
                f"output directory is not empty: {path}; pass --clean for a build/ subtree"
            )
        if not _safe_build_subdirectory(path, root):
            raise Core0Error(f"refusing to clean a directory outside {root / 'build'}: {path}")
        shutil.rmtree(path)
    path.mkdir(parents=True, exist_ok=True)


def _invoke(
    command_log: list[dict[str, object]],
    argv: Sequence[str],
    *,
    cwd: Path,
    root: Path,
    timeout_seconds: float,
    env: Mapping[str, str] | None = None,
) -> None:
    result = checked(argv, cwd=cwd, timeout_seconds=timeout_seconds, env=env)
    command_log.append(
        {
            "argv": list(argv),
            "cwd": _display(cwd, root),
            "returncode": result.returncode,
            "elapsed_seconds": round(result.elapsed_seconds, 6),
            "stdout": result.stdout.decode("utf-8", errors="replace"),
            "stderr": result.stderr.decode("utf-8", errors="replace"),
        }
    )


def _version(tool: str, root: Path) -> str:
    candidates = {
        "lean": ("lean", "--version"),
        "lake": ("lake", "--version"),
        "opt": ("opt", "--version"),
        "llc": ("llc", "--version"),
        "clang": ("clang", "--version"),
        "ld.lld": ("ld.lld", "--version"),
        "qemu-system-riscv64": ("qemu-system-riscv64", "--version"),
        "dtc": ("dtc", "--version"),
    }
    result = checked(candidates[tool], cwd=root, timeout_seconds=15)
    text = (result.stdout + result.stderr).decode("utf-8", errors="replace").strip()
    if not text:
        raise Core0Error(f"{tool} produced an empty version identity")
    return text


def _source_hashes(root: Path, export_source: Path) -> list[dict[str, str]]:
    paths: list[Path] = []
    paths.extend(root / value for value in SOURCE_INPUTS)
    paths.extend(sorted((root / "Lemma").rglob("*.lean")))
    paths.append(root / "Lemma.lean")
    paths.append(root / "examples/core0/Positive.lean")
    paths.append(export_source)
    unique: dict[Path, None] = {}
    for path in paths:
        unique[path.resolve()] = None
    missing = [str(path) for path in unique if not path.is_file()]
    if missing:
        raise Core0Error("missing source/configuration inputs: " + ", ".join(missing))
    return [
        {"path": _display(path, root), "sha256": sha256(path)}
        for path in sorted(unique, key=lambda item: _display(item, root))
    ]


def _git_metadata(root: Path) -> tuple[str, list[str]]:
    commit_result = checked(
        ("git", "rev-parse", "HEAD"), cwd=root, timeout_seconds=15
    )
    commit = commit_result.stdout.decode("ascii", errors="strict").strip()
    if len(commit) != 40:
        raise Core0Error(f"unexpected Git commit identity: {commit!r}")
    status_result = checked(
        ("git", "status", "--porcelain=v1", "--untracked-files=all"),
        cwd=root,
        timeout_seconds=15,
    )
    dirty = status_result.stdout.decode("utf-8", errors="strict").splitlines()
    return commit, dirty


def capture_platform_dtb(
    *,
    output_dir: Path,
    root: Path,
    command_log: list[dict[str, object]],
    timeout_seconds: float,
) -> tuple[Path, Path, list[str]]:
    """Capture QEMU's deterministic machine DTB without booting guest code."""
    qemu_argv = [
        "qemu-system-riscv64",
        "-machine",
        "virt,acpi=off,dumpdtb=platform.dtb",
        "-accel",
        "tcg",
        "-cpu",
        "rv64",
        "-smp",
        "1",
        "-m",
        "128M",
        "-bios",
        "none",
        "-nodefaults",
        "-nic",
        "none",
        "-display",
        "none",
        "-serial",
        "none",
        "-monitor",
        "none",
        "-no-reboot",
        "-seed",
        "1",
    ]
    _invoke(
        command_log,
        qemu_argv,
        cwd=output_dir,
        root=root,
        timeout_seconds=timeout_seconds,
    )
    dtb = output_dir / "platform.dtb"
    if not dtb.is_file() or dtb.stat().st_size == 0:
        raise Core0Error("QEMU did not create a nonempty platform.dtb")
    dts_argv = ["dtc", "-I", "dtb", "-O", "dts", "-o", "platform.dts", "platform.dtb"]
    _invoke(
        command_log,
        dts_argv,
        cwd=output_dir,
        root=root,
        timeout_seconds=timeout_seconds,
    )
    dts = output_dir / "platform.dts"
    if not dts.is_file() or dts.stat().st_size == 0:
        raise Core0Error("dtc did not create a nonempty platform.dts")
    return dtb, dts, qemu_argv


def build(
    *,
    root: Path,
    output_dir: Path,
    opt_level: str,
    export_source: Path,
    clean: bool = False,
    build_lean: bool = True,
    timeout_seconds: float = 180.0,
) -> dict[str, object]:
    if opt_level not in OPT_PASSES:
        raise Core0Error(f"unsupported optimization profile: {opt_level}")
    tools = require_tools(
        (
            "git",
            "lean",
            "lake",
            "opt",
            "llc",
            "clang",
            "ld.lld",
            "qemu-system-riscv64",
            "dtc",
        )
    )
    export_source = export_source.resolve()
    if not export_source.is_file():
        raise Core0Error(f"Lean export driver is missing: {export_source}")
    prepare_output_directory(output_dir, root, clean=clean)
    commands: list[dict[str, object]] = []

    if build_lean:
        _invoke(
            commands,
            ("lake", "build"),
            cwd=root,
            root=root,
            timeout_seconds=timeout_seconds,
        )

    # `examples` is deliberately outside the Lemma library.  Produce its olean
    # through Lean elaboration so the export driver imports the exact checked source.
    positive_olean = root / ".lake/build/lib/lean/examples/core0/Positive.olean"
    positive_olean.parent.mkdir(parents=True, exist_ok=True)
    _invoke(
        commands,
        (
            "lake",
            "env",
            "lean",
            "-o",
            str(positive_olean.relative_to(root)),
            "examples/core0/Positive.lean",
        ),
        cwd=root,
        root=root,
        timeout_seconds=timeout_seconds,
    )

    export_env = os.environ.copy()
    export_env["LEMMA_CORE0_OUT"] = str(output_dir.resolve())
    _invoke(
        commands,
        ("lake", "env", "lean", str(export_source)),
        cwd=root,
        root=root,
        timeout_seconds=timeout_seconds,
        env=export_env,
    )
    missing = [name for name in GENERATED_BY_LEAN if not (output_dir / name).is_file()]
    if missing:
        raise Core0Error("Lean exporter omitted artifacts: " + ", ".join(missing))

    opt_argv = [
        "opt",
        "-S",
        f"-passes={OPT_PASSES[opt_level]}",
        "program.ll",
        "-o",
        "program.opt.ll",
    ]
    _invoke(
        commands,
        opt_argv,
        cwd=output_dir,
        root=root,
        timeout_seconds=timeout_seconds,
    )

    llc_argv = [
        "llc",
        *LLC_ARGUMENTS,
        f"-{opt_level}",
        "program.opt.ll",
        "-o",
        "program.o",
    ]
    _invoke(
        commands,
        llc_argv,
        cwd=output_dir,
        root=root,
        timeout_seconds=timeout_seconds,
    )

    startup_argv = ["clang", *STARTUP_ARGUMENTS, "startup.S", "-o", "startup.o"]
    _invoke(
        commands,
        startup_argv,
        cwd=output_dir,
        root=root,
        timeout_seconds=timeout_seconds,
    )

    link_argv = [
        "ld.lld",
        *LINK_ARGUMENTS,
        "-o",
        "image.elf",
        "startup.o",
        "program.o",
    ]
    _invoke(
        commands,
        link_argv,
        cwd=output_dir,
        root=root,
        timeout_seconds=timeout_seconds,
    )
    dtb, dts, qemu_dtb_argv = capture_platform_dtb(
        output_dir=output_dir,
        root=root,
        command_log=commands,
        timeout_seconds=30.0,
    )

    required_outputs = (
        *GENERATED_BY_LEAN,
        "program.opt.ll",
        "program.o",
        "startup.o",
        "image.elf",
        "image.map",
        "platform.dtb",
        "platform.dts",
    )
    missing = [name for name in required_outputs if not (output_dir / name).is_file()]
    empty = [
        name
        for name in required_outputs
        if (output_dir / name).is_file() and (output_dir / name).stat().st_size == 0
    ]
    if missing or empty:
        raise Core0Error(
            f"incomplete target output (missing={missing!r}, empty={empty!r})"
        )

    commit, dirty_paths = _git_metadata(root)
    versions = {
        name: {"path": tools[name], "version": _version(name, root)}
        for name in (
            "lean",
            "lake",
            "opt",
            "llc",
            "clang",
            "ld.lld",
            "qemu-system-riscv64",
            "dtc",
        )
    }
    linked_inputs = [
        {
            "path": "startup.o",
            "kind": "lean-structured-startup",
            "sha256": sha256(output_dir / "startup.o"),
            "generation_command": startup_argv,
            "source": "startup.S generated by Lemma.Machine.Primitives",
            "purpose": "M-mode entry, BSS clearing, a0/a1 boot-input preservation, and I/O fence",
        },
        {
            "path": "program.o",
            "kind": "core0-llvm",
            "sha256": sha256(output_dir / "program.o"),
            "generation_command": llc_argv,
            "source": "program.ll generated from the checked elaborated Core0 program",
            "purpose": "compiled Core0 application and freestanding machine harness",
        },
    ]
    provenance: dict[str, object] = {
        "schema_version": 1,
        "source_commit": commit,
        "dirty_tree": bool(dirty_paths),
        "dirty_paths": dirty_paths,
        "compiler_route": "Lean Environment declaration bodies -> checked Core0 -> structured LLVM -> LLVM RV64",
        "optimization": opt_level,
        "target": {
            "triple": "riscv64-unknown-elf",
            "llvm_triple": "riscv64-unknown-unknown-elf",
            "abi": "lp64",
            "isa": "rv64im_zicsr_zifencei",
            "linker": "ld.lld direct (no driver defaults or target libraries)",
        },
        "source_inputs": _source_hashes(root, export_source),
        "linked_inputs": linked_inputs,
        "link_command": link_argv,
        "tools": versions,
        "emulator_artifacts": [
            {
                "path": "platform.dtb",
                "sha256": sha256(dtb),
                "source": "pinned QEMU virt machine dumpdtb",
                "generation_command": qemu_dtb_argv,
            },
            {
                "path": "platform.dts",
                "sha256": sha256(dts),
                "source": "dtc decompilation of platform.dtb",
                "generation_command": [
                    "dtc",
                    "-I",
                    "dtb",
                    "-O",
                    "dts",
                    "-o",
                    "platform.dts",
                    "platform.dtb",
                ],
            },
        ],
        "commands": commands,
    }
    write_json(output_dir / "provenance.json", provenance)
    artifact_hashes = {
        name: sha256(output_dir / name)
        for name in sorted((*required_outputs, "provenance.json"))
    }
    record: dict[str, object] = {
        "schema_version": 1,
        "status": "pass",
        "optimization": opt_level,
        "output_directory": _display(output_dir, root),
        "artifacts": artifact_hashes,
        "linked_inputs": linked_inputs,
        "platform_dtb_sha256": sha256(dtb),
    }
    write_json(output_dir / "build.json", record)
    return record


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--opt-level", choices=sorted(OPT_PASSES), default="O2")
    parser.add_argument("--output-dir", type=Path)
    parser.add_argument("--export-source", type=Path, default=Path("examples/core0/Build.lean"))
    parser.add_argument("--clean", action="store_true")
    parser.add_argument("--timeout", type=float, default=180.0)
    ns = parser.parse_args()
    root = repo_root()
    output = ns.output_dir or Path(f"build/core0/{ns.opt_level}")
    output = (root / output).resolve() if not output.is_absolute() else output.resolve()
    source = (
        (root / ns.export_source).resolve()
        if not ns.export_source.is_absolute()
        else ns.export_source.resolve()
    )
    try:
        record = build(
            root=root,
            output_dir=output,
            opt_level=ns.opt_level,
            export_source=source,
            clean=ns.clean,
            timeout_seconds=ns.timeout,
        )
    except (Core0Error, OSError, ValueError, json.JSONDecodeError) as error:
        print(f"CORE0 BUILD FAIL: {error}", file=sys.stderr)
        return 1
    print(json.dumps(record, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
