import ast
import inspect
import tempfile
import sys
from pathlib import Path
from types import SimpleNamespace
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'scripts'))
from silicon_hold_decode import require_recipe, assess, completed_route_inputs
from silicon_pen_physical import prepared_assessment_script


class JointRecipe(unittest.TestCase):
    def arguments(self, **changes):
        values = dict(hold_decode_from=Path('build/qualified-joint'),
                      routed_eco_from=Path('build/actual-two-load-route'),
                      clock_min_routing_layer='Metal3', detail_route_iterations=8,
                      host_memory_gib=6, selected_implementation=False)
        values.update(changes)
        return SimpleNamespace(**values)

    def test_exact_unselected_recipe(self):
        require_recipe(self.arguments())

    def test_declared_resource_and_route_controls_cannot_drift(self):
        for changes in (dict(clock_min_routing_layer='Metal2'),
                        dict(detail_route_iterations=3), dict(host_memory_gib=4),
                        dict(routed_eco_from=None), dict(selected_implementation=True)):
            with self.subTest(changes=changes), self.assertRaises(ValueError):
                require_recipe(self.arguments(**changes))

    def test_real_preparation_call_retains_fixed_reference(self):
        fixed = Path('build/qualified-joint/unrouted.odb')
        source = prepared_assessment_script('silicon_hold_decode', Path('old.odb'), fixed,
            Path('original.lib'), Path('evidence.json'), fixed_geometry=fixed)
        calls = [node for node in ast.walk(ast.parse(source)) if isinstance(node, ast.Call)
                 and isinstance(node.func, ast.Name) and node.func.id == 'assess']
        self.assertEqual(len(calls), 1)
        self.assertEqual([key.arg for key in calls[0].keywords], ['fixed_geometry'])
        self.assertEqual(ast.literal_eval(calls[0].keywords[0].value.args[0]), str(fixed))
        with self.assertRaises(ValueError):
            prepared_assessment_script('silicon_hold_decode', Path('old.odb'), fixed,
                                       Path('original.lib'), Path('evidence.json'))
        legacy = prepared_assessment_script('silicon_two_load_launch', Path('old.odb'),
                                            fixed, Path('original.lib'), Path('evidence.json'))
        self.assertNotIn('fixed_geometry=', legacy)

    def test_preparation_and_final_exports_cannot_collide(self):
        # Exercise the actual output-directory expression used by the native
        # relation with the two names generated by the ordinary flow.
        calls = [node for node in ast.walk(ast.parse(inspect.getsource(assess)))
                 if isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
                 and node.func.id == 'master_library_relation']
        self.assertEqual(len(calls), 1)
        expression = compile(ast.Expression(calls[0].args[2]), '<actual-master-output>', 'eval')
        with tempfile.TemporaryDirectory() as directory:
            names = ('padded-hold-preparation.json', 'padded-hold-endpoints.json')
            paths = [eval(expression, {'Path': Path, 'output': Path(directory) / name})
                     for name in names]
            self.assertNotEqual(*paths)
            for path in paths:
                path.mkdir()
            with self.assertRaises(FileExistsError):
                paths[0].mkdir()  # Existing same-result output still rejects.
            old = [Path(directory) / 'joint-master-library' for _ in names]
            self.assertEqual(*old)  # Historical constant namespace cannot pass.

    def test_completed_mode_requires_exact_source_and_failed_receipt(self):
        require_recipe(self.arguments(completed_hold_decode_route_from=Path('closed')))
        with self.assertRaises(ValueError):
            require_recipe(self.arguments(hold_decode_from=None,
                completed_hold_decode_route_from=Path('closed')))
        with tempfile.TemporaryDirectory() as directory:
            Path(directory, 'result.json').write_text('{"status":"FAIL"}')
            with self.assertRaises(ValueError):
                completed_route_inputs(Path(directory))

    def test_no_mixed_geometry_or_completion_recipe(self):
        for flag in ('two_load_launch_from', 'well_fill_from', 'fresh_core_power_grid',
                     'preserve_routed_netlist', 'completed_well_fill_route_from',
                     'preferred_access_from', 'group_button_bus'):
            with self.subTest(flag=flag), self.assertRaises(ValueError):
                require_recipe(self.arguments(**{flag: True}))


if __name__ == '__main__':
    unittest.main()
